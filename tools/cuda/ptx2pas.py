"""LandrixAI - PTX modules as Pascal constants.

usage: ptx2pas.py out.inc name1=file1.ptx [name2=file2.ptx ...]

Writes one `array of cardinal` constant per module: the PTX text, zero
terminated as cuModuleLoadData expects it, zero padded to whole words
(little-endian) - so the engine needs no CUDA compiler and no file at run
time, and Delphi 7 no string constant longer than it allows. Generated by
tools/cuda/build-kernels.sh - do not edit the output.
"""
import struct
import sys


def main():
    out = sys.argv[1]
    lines = ["// generated by tools/cuda/build-kernels.sh from tools/cuda/*.cu - do not edit", ""]
    lines.append("const")
    for arg in sys.argv[2:]:
        name, path = arg.split("=", 1)
        data = open(path, "rb").read()
        if not data.lstrip().startswith(b"//") or b".entry" not in data:
            raise SystemExit("%s: no PTX module" % path)
        if b"\0" in data:
            raise SystemExit("%s: a zero byte inside the PTX text" % path)
        data += b"\0"
        data += b"\0" * (-len(data) % 4)
        words = struct.unpack("<%dI" % (len(data) // 4), data)
        lines.append("  %s: array[0..%d] of cardinal = (" % (name, len(words) - 1))
        for i in range(0, len(words), 8):
            chunk = ", ".join("$%08x" % w for w in words[i:i + 8])
            last = i + 8 >= len(words)
            lines.append("    " + chunk + (");" if last else ","))
        lines.append("")
    open(out, "w", newline="\n").write("\n".join(lines))


main()
