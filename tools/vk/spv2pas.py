"""LandrixAI - SPIR-V binaries as Pascal constants.

usage: spv2pas.py out.inc name1=file1.spv [name2=file2.spv ...]

Writes one `array of cardinal` constant per shader (little-endian words, as
SPIR-V is stored), so the engine needs no shader compiler and no file at run
time. Generated by tools/vk/build-shaders.sh - do not edit the output.
"""
import struct
import sys


def main():
    out = sys.argv[1]
    lines = ["// generated by tools/vk/build-shaders.sh from tools/vk/*.comp - do not edit", ""]
    lines.append("const")
    for arg in sys.argv[2:]:
        name, path = arg.split("=", 1)
        data = open(path, "rb").read()
        if len(data) % 4 != 0 or struct.unpack_from("<I", data)[0] != 0x07230203:
            raise SystemExit("%s: not a little-endian SPIR-V module" % path)
        words = struct.unpack("<%dI" % (len(data) // 4), data)
        lines.append("  %s: array[0..%d] of cardinal = (" % (name, len(words) - 1))
        for i in range(0, len(words), 8):
            chunk = ", ".join("$%08x" % w for w in words[i:i + 8])
            last = i + 8 >= len(words)
            lines.append("    " + chunk + (");" if last else ","))
        lines.append("")
    open(out, "w", newline="\n").write("\n".join(lines))


main()
